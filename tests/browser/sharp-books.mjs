import {createServer} from 'node:http';
import {readFile} from 'node:fs/promises';
import {resolve,extname} from 'node:path';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(process.env.EDGE_LAB_BROWSER_PACKAGE||import.meta.url);
const {chromium}=require('playwright');
const root=resolve('sharp-service');
const server=createServer(async(req,res)=>{try{const path=resolve(root,'.'+new URL(req.url,'http://localhost').pathname);if(!path.startsWith(root+'/'))throw Error();res.setHeader('Content-Type',({'.html':'text/html','.js':'text/javascript','.css':'text/css'})[extname(path)]||'text/plain');res.end(await readFile(path));}catch{res.writeHead(404);res.end();}});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
let browser;
try{
 browser=await chromium.launch({headless:true,...(process.env.EDGE_LAB_CHROMIUM?{executablePath:process.env.EDGE_LAB_CHROMIUM}:{})});
 const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];page.on('pageerror',e=>errors.push(e.message));
 const now=new Date().toISOString(),future=new Date(Date.now()+3600000).toISOString();
 const data={generatedAt:now,source:'Synthetic fixture',events:[],comparisonLines:[{eventID:'fixture',playerID:'player',playerName:'Fixture Player',startsAt:future,market:'points',side:'over',book:'prizepicks',line:20.5,updatedAt:now}],coverage:{bookmakerCoverage:{pinnacle:{status:'NOT_OBSERVED'},circa:{status:'NOT_OBSERVED'},prizepicks:{status:'LINE_ONLY'}}}};
 await page.route('**/api/**',r=>{const url=new URL(r.request().url());if(url.pathname==='/api/nbaprops')assert.equal(url.searchParams.get('research'),'1');return r.fulfill({json:url.pathname.includes('nflprops')?{candidates:[],generatedAt:now}:data});});
 await page.goto(`http://127.0.0.1:${server.address().port}/research.html`);
 await page.getByRole('heading',{name:'Fixture Player',exact:true}).waitFor();
 assert.match(await page.locator('#status').innerText(),/Pinnacle: not observed/);
 assert.match(await page.locator('.card').innerText(),/Comparison line only/);
 assert.match(await page.locator('.card').innerText(),/NOT CLEARED/);
 assert.doesNotMatch(await page.locator('.comparison').innerText(),/\d+\.\d+%/);
 await page.locator('#book').selectOption('prizepicks');
 await page.getByRole('button',{name:'Why isn’t this cleared?'}).click();
 assert.match(await page.locator('#detail-body').innerText(),/No probability is inferred/);
 await page.getByRole('button',{name:'Close quote details'}).click();
 assert.equal(await page.locator('#detail').evaluate(e=>e.open),false);
 await page.getByRole('button',{name:'Shortlist +'}).click();
 await page.getByRole('button',{name:'View shortlist'}).click();
 assert.match(await page.locator('.card').innerText(),/Comparison line only/);
 await page.getByRole('button',{name:'Back to board'}).click();
 await page.locator('[data-sport="NFL"]').click();await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('NFL'));
 assert.equal(await page.locator('.card').count(),0);
 await page.locator('[data-sport="NBA"]').click();await page.getByRole('heading',{name:'Fixture Player',exact:true}).waitFor();
 await page.locator('#refresh').click();await page.getByRole('heading',{name:'Fixture Player',exact:true}).waitFor();
 assert.deepEqual(errors,[]);
 console.log('Sharp book coverage / PrizePicks mobile display, filters, modal, shortlist, sport switching and refresh passed.');
}finally{await browser?.close();server.close();}
