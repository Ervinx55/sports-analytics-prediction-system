
create table if not exists public.model_audit_observations (
  id bigint generated by default as identity primary key,
  captured_at timestamptz not null default now(),
  sport text not null default 'MLB',
  model_version text,
  verification_version text,
  event_id text not null,
  game_pk bigint,
  starts_at timestamptz,
  away_team text,
  home_team text,
  side_key text not null,
  side_name text not null,
  model_decision text,
  verification_status text,
  best_book text,
  best_odds integer,
  playable_threshold integer,
  base_probability numeric,
  final_probability numeric,
  edge_pct_points numeric,
  ev_pct numeric,
  lineup_adjustment_pp numeric,
  platoon_adjustment_pp numeric,
  pitchmix_adjustment_pp numeric,
  bullpen_adjustment_pp numeric,
  runenv_adjustment_pp numeric,
  blockers jsonb not null default '[]'::jsonb,
  warnings jsonb not null default '[]'::jsonb,
  raw jsonb,
  unique (event_id, side_key, captured_at)
);

create index if not exists model_audit_event_idx
  on public.model_audit_observations(event_id, side_key, captured_at desc);

create index if not exists model_audit_start_idx
  on public.model_audit_observations(starts_at);

create table if not exists public.game_results (
  event_id text primary key,
  sport text not null default 'MLB',
  game_pk bigint,
  starts_at timestamptz,
  away_team text,
  home_team text,
  away_score integer,
  home_score integer,
  total_runs integer,
  winner_side text,
  final_status text,
  graded_at timestamptz not null default now(),
  raw jsonb
);

create table if not exists public.candidate_grades (
  audit_id bigint primary key references public.model_audit_observations(id) on delete cascade,
  event_id text not null,
  side_key text not null,
  result text,
  won boolean,
  closing_book text,
  closing_odds integer,
  closing_fair_probability numeric,
  model_probability numeric,
  probability_clv_pp numeric,
  price_clv_cents integer,
  closing_captured_at timestamptz,
  graded_at timestamptz not null default now(),
  raw jsonb
);

create index if not exists candidate_grades_event_idx
  on public.candidate_grades(event_id, side_key);

create table if not exists public.model_registry (
  model_version text primary key,
  sport text not null,
  status text not null default 'frozen',
  frozen_at timestamptz not null default now(),
  notes text
);

insert into public.model_registry(model_version, sport, status, notes)
values (
  'MLB-v7-audit',
  'MLB',
  'frozen',
  'Freeze current decision/verification logic for audit. Fix data bugs immediately, but do not retune weights from short-term wins/losses.'
