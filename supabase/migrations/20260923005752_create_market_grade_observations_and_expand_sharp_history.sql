
    alter table public.sharp_gate_history
      add column if not exists market_type text,
      add column if not exists market_side text,
      add column if not exists market_line numeric;

    update public.sharp_gate_history
    set market_type = coalesce(market_type, 'moneyline'),
        market_side = coalesce(market_side, side_key)
    where market_type is null or market_side is null;

    drop view if exists public.sharp_gate_latest;
    create view public.sharp_gate_latest as
    with ranked as (
      select
        s.*,
        row_number() over (
          partition by
            coalesce(event_id, ''),
            coalesce(market_type, 'moneyline'),
            coalesce(market_side, side_key, ''),
            coalesce(market_line::text, '')
          order by checked_at desc, id desc
        ) as rn
      from public.sharp_gate_history s
    )
    select *
    from ranked
    where rn = 1;

    create table if not exists public.market_grade_observations (
      id bigint generated by default as identity primary key,
      captured_at timestamptz not null default now(),
      sport text not null default 'MLB',
      model_version text,
      event_id text not null,
      game_pk bigint,
      starts_at timestamptz,
      away_team text,
      home_team text,
      market_type text not null,
      market_side text not null,
      market_label text not null,
      line numeric,
      best_book text,
      best_odds integer,
      playable_threshold integer,
      model_probability numeric,
      market_fair_probability numeric,
      edge_pct_points numeric,
      ev_pct numeric,
      non_sharp_status text not null,
      requires_sharp boolean not null default false,
      reason text,
      raw jsonb not null default '{}'::jsonb
    );

    create index if not exists market_grade_lookup_idx
      on public.market_grade_observations(
        sport, event_id, market_type, market_side, captured_at desc
      );

    create or replace view public.market_grade_latest as
    with ranked as (
      select
        m.*,
        row_number() over (
          partition by
            sport,
            event_id,
            market_type,
            market_side,
            coalesce(line::text, '')
          order by captured_at desc, id desc
        ) as rn
      from public.market_grade_observations m
    )
    select *
    from ranked
    where rn = 1;

    alter table public.market_grade_observations enable row level security;
  
