
    create table if not exists public.player_prop_observations (
      id bigint generated by default as identity primary key,
      captured_at timestamptz not null default now(),
      sport text not null default 'MLB',
      model_version text not null,
      event_id text not null,
      game_pk bigint,
      starts_at timestamptz,
      away_team text,
      home_team text,
      player_id text,
      mlb_player_id bigint,
      player_name text not null,
      stat_id text not null,
      market_name text,
      line numeric not null,
      side text not null,
      label text not null,
      model_mean numeric,
      raw_independent_probability numeric,
      model_probability numeric,
      push_probability numeric,
      market_fair_probability numeric,
      edge_pct_points numeric,
      best_book text,
      best_odds integer,
      exact_line_book_count integer,
      paired_books integer,
      ev_pct numeric,
      data_quality numeric,
      status text not null,
      reason text,
      raw jsonb not null default '{}'::jsonb
    );

    create index if not exists player_prop_lookup_idx
      on public.player_prop_observations(
        event_id, player_id, stat_id, line, side, captured_at desc
      );

    create or replace view public.player_prop_latest as
    with ranked as (
      select
        p.*,
        row_number() over (
          partition by event_id, player_id, stat_id, line, side
          order by captured_at desc, id desc
        ) as rn
      from public.player_prop_observations p
    )
    select *
    from ranked
    where rn = 1;

    create table if not exists public.player_prop_results (
      observation_id bigint primary key
        references public.player_prop_observations(id) on delete cascade,
      event_id text not null,
      game_pk bigint,
      player_id text,
      mlb_player_id bigint,
      stat_id text not null,
      line numeric not null,
      side text not null,
      actual_value numeric,
      outcome text,
      won boolean,
      pushed boolean not null default false,
      graded_at timestamptz not null default now(),
      raw jsonb not null default '{}'::jsonb
    );

    create index if not exists player_prop_results_event_idx
      on public.player_prop_results(event_id, player_id, stat_id);

    alter table public.player_prop_observations enable row level security;
    alter table public.player_prop_results enable row level security;
  
