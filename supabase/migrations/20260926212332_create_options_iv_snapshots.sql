
create table if not exists public.options_iv_snapshots (
  id bigint generated by default as identity primary key,
  symbol text not null check (symbol = upper(symbol)),
  tenor_days integer not null default 30 check (tenor_days between 1 and 365),
  captured_on date not null default current_date,
  captured_at timestamptz not null default now(),
  expiration date not null,
  dte integer not null check (dte >= 0),
  underlying_price numeric(18,6) not null check (underlying_price > 0),
  atm_strike numeric(18,6) not null check (atm_strike > 0),
  atm_iv numeric(12,6) not null check (atm_iv >= 0),
  call_iv numeric(12,6),
  put_iv numeric(12,6),
  provider text not null default 'tradier',
  unique (symbol, tenor_days, captured_on)
);

create index if not exists options_iv_snapshots_symbol_tenor_date_idx
  on public.options_iv_snapshots (symbol, tenor_days, captured_on desc);

alter table public.options_iv_snapshots enable row level security;

revoke all on table public.options_iv_snapshots from anon, authenticated;
grant select, insert, update on table public.options_iv_snapshots to service_role;
grant usage, select on sequence public.options_iv_snapshots_id_seq to service_role;
