
create table if not exists public.sharp_source_quotes (
  id bigint generated by default as identity primary key,
  observed_at timestamptz not null default now(),
  sport text not null default 'MLB',
  source_book text not null,
  provider text not null,
  source_kind text not null,
  source_event_key text,
  event_date date,
  starts_at timestamptz,
  away_team text,
  home_team text,
  market_type text not null,
  market_side text not null,
  line numeric,
  odds integer,
  opponent_odds integer,
  source_updated_at timestamptz,
  freshness_basis text,
  source_url text,
  raw jsonb not null default '{}'::jsonb
);

alter table public.sharp_source_quotes enable row level security;

create index if not exists sharp_source_quotes_lookup_idx
  on public.sharp_source_quotes(
    sport, source_book, event_date, market_type, market_side, observed_at desc
  );

create index if not exists sharp_source_quotes_matchup_idx
  on public.sharp_source_quotes(
    sport, away_team, home_team, event_date, observed_at desc
  );

create or replace view public.sharp_source_quote_latest
with (security_invoker = true)
as
with ranked as (
  select q.*,
         row_number() over (
           partition by
             q.sport,
             q.source_book,
             coalesce(q.source_event_key,''),
             q.market_type,
             q.market_side,
             coalesce(q.line::text,'')
           order by q.observed_at desc, q.id desc
         ) as rn
  from public.sharp_source_quotes q
)
select *
from ranked
where rn=1;

grant select, insert on public.sharp_source_quotes to service_role;
grant usage, select on sequence public.sharp_source_quotes_id_seq to service_role;
grant select on public.sharp_source_quote_latest to service_role;
