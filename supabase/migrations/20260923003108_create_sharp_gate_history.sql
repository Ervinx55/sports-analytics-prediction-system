
    create table if not exists public.sharp_gate_history (
      id bigint generated by default as identity primary key,
      checked_at timestamptz not null default now(),
      sport text not null default 'MLB',
      event_id text,
      game_pk bigint,
      starts_at timestamptz,
      away_team text,
      home_team text,
      side_key text,
      side_name text,
      verification_status text,
      mainstream_book text,
      mainstream_odds integer,
      playable_threshold integer,
      model_probability numeric,
      bookmaker_away_odds integer,
      bookmaker_home_odds integer,
      bookmaker_candidate_fair_probability numeric,
      bookmaker_freshness text,
      pinnacle_away_odds integer,
      pinnacle_home_odds integer,
      pinnacle_candidate_fair_probability numeric,
      pinnacle_status text,
      pinnacle_freshness text,
      circa_away_odds integer,
      circa_home_odds integer,
      circa_candidate_fair_probability numeric,
      circa_status text,
      circa_freshness text,
      model_vs_bookmaker_pp numeric,
      sharp_disagreement_pp numeric,
      price_ok boolean,
      second_source_ok boolean,
      final_status text not null,
      reason text,
      raw jsonb not null default '{}'::jsonb
    );

    create index if not exists sharp_gate_event_idx
      on public.sharp_gate_history(event_id, side_key, checked_at desc);

    create index if not exists sharp_gate_status_idx
      on public.sharp_gate_history(final_status, checked_at desc);

    create or replace view public.sharp_gate_latest as
    with ranked as (
      select
        s.*,
        row_number() over (
          partition by coalesce(event_id, ''), coalesce(side_key, '')
          order by checked_at desc, id desc
        ) as rn
      from public.sharp_gate_history s
    )
    select *
    from ranked
    where rn = 1;

    alter table public.sharp_gate_history enable row level security;
  
