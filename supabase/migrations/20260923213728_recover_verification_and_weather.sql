CREATE OR REPLACE FUNCTION public.compute_weather_park_impact_v1(p_park_factor numeric, p_park_factor_known boolean, p_temp_f numeric, p_humidity_pct numeric, p_wind_mph numeric, p_wind_class text, p_roof_type text, p_roof_status text, p_precip_probability_pct numeric, p_precip_inches numeric, p_condition text, p_elevation_ft numeric)
 RETURNS jsonb
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO 'pg_catalog', 'public'
AS $function$
declare
  v_pf numeric := coalesce(p_park_factor,100);
  v_park numeric := greatest(0.88,least(1.14,v_pf/100.0));
  v_park_hr numeric := greatest(0.84,least(1.18,1 + (v_park-1)*1.25));
  v_park_hit numeric := greatest(0.90,least(1.12,1 + (v_park-1)*0.65));
  v_roof_type text := lower(coalesce(p_roof_type,''));
  v_roof_status text := upper(coalesce(p_roof_status,''));
  v_weather_active boolean := false;
  v_alt numeric := 1 + greatest(0,least(1,coalesce(p_elevation_ft,0)/5200.0))*0.15;

  v_temp_run numeric := 1;
  v_temp_hr numeric := 1;
  v_temp_hit numeric := 1;
  v_hum_run numeric := 1;
  v_hum_hr numeric := 1;
  v_hum_hit numeric := 1;
  v_wind_run numeric := 1;
  v_wind_hr numeric := 1;
  v_wind_hit numeric := 1;

  v_wind_class text := upper(coalesce(p_wind_class,'UNKNOWN'));
  v_strength numeric := greatest(0,least(3,coalesce(p_wind_mph,0)/10.0));

  v_run numeric;
  v_hr numeric;
  v_hit numeric;
  v_dur numeric := 1;
  v_k numeric;
  v_delay text := 'LOW';
  v_quality numeric := 1;
  v_state text := 'READY';

  v_reasons jsonb := '[]'::jsonb;
  v_warnings jsonb := '[]'::jsonb;
  v_temp_delta numeric;
  v_hum_delta numeric;
begin
  if v_roof_status not in ('OPEN','CLOSED') then
    if v_roof_type ~ 'dome' then
      v_roof_status := 'CLOSED';
    elsif v_roof_type = 'open' then
      v_roof_status := 'OPEN';
    elsif v_roof_type ~ 'retractable' then
      v_roof_status := 'UNKNOWN';
    else
      v_roof_status := 'UNKNOWN';
    end if;
  end if;

  v_weather_active := v_roof_status = 'OPEN';

  if v_weather_active then
    if p_temp_f is not null then
      v_temp_delta := ((p_temp_f-70)/10.0)*v_alt;
      v_temp_run := greatest(0.975,least(1.025,1 + v_temp_delta*0.004));
      v_temp_hr := greatest(0.94,least(1.06,1 + v_temp_delta*0.012));
      v_temp_hit := greatest(0.97,least(1.03,1 + v_temp_delta*0.006));
    else
      v_quality := v_quality-0.10;
      v_warnings := v_warnings || jsonb_build_array('Temperature unavailable for an open-air game.');
    end if;

    if p_humidity_pct is not null then
      v_hum_delta := (p_humidity_pct-50)/10.0;
      v_hum_run := greatest(0.99,least(1.01,1 + v_hum_delta*0.001));
      v_hum_hr := greatest(0.98,least(1.02,1 + v_hum_delta*0.002));
      v_hum_hit := greatest(0.99,least(1.01,1 + v_hum_delta*0.001));
    else
      v_quality := v_quality-0.06;
      v_warnings := v_warnings || jsonb_build_array('Humidity unavailable.');
    end if;

    if p_wind_mph is null then
      v_quality := v_quality-0.08;
      v_warnings := v_warnings || jsonb_build_array('Wind speed unavailable.');
    end if;

    if v_wind_class = 'OUT' then
      v_wind_run := greatest(0.96,least(1.04,1 + 0.010*v_strength*v_alt));
      v_wind_hr := greatest(0.90,least(1.10,1 + 0.028*v_strength*v_alt));
      v_wind_hit := greatest(0.95,least(1.05,1 + 0.012*v_strength*v_alt));
    elsif v_wind_class = 'IN' then
      v_wind_run := greatest(0.96,least(1.04,1 - 0.010*v_strength*v_alt));
      v_wind_hr := greatest(0.90,least(1.10,1 - 0.028*v_strength*v_alt));
      v_wind_hit := greatest(0.95,least(1.05,1 - 0.012*v_strength*v_alt));
    elsif v_wind_class in ('CROSS','CALM') then
      null;
    else
      v_quality := v_quality-0.06;
      v_warnings := v_warnings || jsonb_build_array('Wind direction could not be classified as in/out/cross.');
    end if;

    if p_precip_probability_pct is null then
      v_quality := v_quality-0.06;
      v_warnings := v_warnings || jsonb_build_array('Precipitation probability unavailable.');
    end if;

    if coalesce(p_precip_probability_pct,0) >= 70
       or coalesce(p_precip_inches,0) >= 0.08
       or lower(coalesce(p_condition,'')) ~ 'thunder|storm|heavy rain' then
      v_delay := 'HIGH';
      v_dur := least(v_dur,0.90);
      v_warnings := v_warnings || jsonb_build_array('High delay/interruption risk may shorten starter workload.');
    elsif coalesce(p_precip_probability_pct,0) >= 40
       or coalesce(p_precip_inches,0) >= 0.03
       or lower(coalesce(p_condition,'')) ~ 'rain|shower' then
      v_delay := 'MEDIUM';
      v_dur := least(v_dur,0.95);
      v_warnings := v_warnings || jsonb_build_array('Meaningful precipitation risk may affect starter workload.');
    elsif coalesce(p_precip_probability_pct,0) >= 20
       or coalesce(p_precip_inches,0) > 0 then
      v_delay := 'WATCH';
      v_dur := least(v_dur,0.98);
    end if;

    if p_temp_f is not null then
      if p_temp_f >= 100 then
        v_dur := v_dur*0.97;
        v_warnings := v_warnings || jsonb_build_array('Extreme heat modestly reduces starter durability assumption.');
      elsif p_temp_f >= 95 then
        v_dur := v_dur*0.985;
      elsif p_temp_f <= 40 then
        v_dur := v_dur*0.99;
      end if;
    end if;
  elsif v_roof_status = 'CLOSED' then
    v_delay := 'LOW';
    v_reasons := v_reasons || jsonb_build_array('Closed/dome roof suppresses outdoor weather effects.');
  else
    v_quality := v_quality-0.25;
    v_state := 'PENDING';
    v_reasons := v_reasons || jsonb_build_array('Retractable/unknown roof status is not verified.');
  end if;

  if coalesce(p_park_factor_known,false) = false then
    v_quality := v_quality-0.08;
    v_warnings := v_warnings || jsonb_build_array('Park factor is using a neutral fallback.');
  end if;

  v_run := greatest(0.84,least(1.20,v_park*v_temp_run*v_hum_run*v_wind_run));
  v_hr := greatest(0.78,least(1.28,v_park_hr*v_temp_hr*v_hum_hr*v_wind_hr));
  v_hit := greatest(0.88,least(1.16,v_park_hit*v_temp_hit*v_hum_hit*v_wind_hit));
  v_dur := greatest(0.82,least(1.02,v_dur));
  v_k := greatest(0.85,least(1.05,v_dur*(1 - (v_run-1)*0.12)));

  v_quality := greatest(0,least(1,v_quality));
  if v_state <> 'PENDING' and v_quality < 0.65 then
    v_state := 'PENDING';
    v_reasons := v_reasons || jsonb_build_array('Weather/park data quality is below the shadow-model minimum.');
  elsif v_state <> 'PENDING' and v_delay = 'HIGH' then
    v_state := 'WEATHER_RISK';
  end if;

  return jsonb_build_object(
    'evaluatorVersion','weather-park-v1',
    'state',v_state,
    'roofStatus',v_roof_status,
    'weatherApplied',v_weather_active,
    'delayRisk',v_delay,
    'dataQuality',round(v_quality,3),
    'parkMultiplier',round(v_park,4),
    'temperatureRunMultiplier',round(v_temp_run,4),
    'humidityRunMultiplier',round(v_hum_run,4),
    'windRunMultiplier',round(v_wind_run,4),
    'runMultiplier',round(v_run,4),
    'teamRunMultiplier',round(v_run,4),
    'hrMultiplier',round(v_hr,4),
    'hitsTbMultiplier',round(v_hit,4),
    'starterDurabilityMultiplier',round(v_dur,4),
    'strikeoutOpportunityMultiplier',round(v_k,4),
    'expectedTotalDeltaRunsAt8_5',round(8.5*(v_run-1),3),
    'runImpact',case when v_run >= 1.025 then 'RUN_UP' when v_run <= 0.975 then 'RUN_DOWN' else 'NEUTRAL' end,
    'hrImpact',case when v_hr >= 1.04 then 'HR_UP' when v_hr <= 0.96 then 'HR_DOWN' else 'NEUTRAL' end,
    'hitsTbImpact',case when v_hit >= 1.02 then 'HITS_TB_UP' when v_hit <= 0.98 then 'HITS_TB_DOWN' else 'NEUTRAL' end,
    'strikeoutImpact',case when v_k >= 1.015 then 'K_OPPORTUNITY_UP' when v_k <= 0.985 then 'K_OPPORTUNITY_DOWN' else 'NEUTRAL' end,
    'components',jsonb_build_object(
      'parkFactor',v_pf,
      'parkFactorKnown',coalesce(p_park_factor_known,false),
      'tempF',p_temp_f,
      'humidityPct',p_humidity_pct,
      'windMph',p_wind_mph,
      'windClass',v_wind_class,
      'precipProbabilityPct',p_precip_probability_pct,
      'precipInches',p_precip_inches,
      'condition',p_condition,
      'elevationFt',p_elevation_ft,
      'altitudeSensitivity',round(v_alt,4)
    ),
    'reasons',v_reasons,
    'warnings',v_warnings
  );
end;
