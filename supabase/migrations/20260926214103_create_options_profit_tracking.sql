
create table if not exists public.options_setup_snapshots (
  id bigint generated by default as identity primary key,
  captured_at timestamptz not null default now(),
  snapshot_bucket timestamptz not null,
  model_version text not null,
  contract_symbol text not null,
  underlying text not null,
  option_type text not null check (option_type in ('CALL','PUT')),
  expiration date not null,
  strike numeric(18,6) not null,
  dte integer not null check (dte >= 0),
  underlying_price numeric(18,6) not null,
  bid numeric(18,6) not null,
  ask numeric(18,6) not null,
  market_iv numeric(12,6),
  forecast_vol numeric(12,6),
  model_fair_value numeric(18,6),
  probability_profit numeric(12,6),
  net_ev_dollars numeric(18,6),
  expected_return_on_risk_pct numeric(12,6),
  spread_pct numeric(12,6),
  estimated_cost_dollars numeric(18,6),
  theta_burden_pct numeric(12,6),
  liquidity_score numeric(12,6),
  profit_score numeric(12,6),
  grade text not null check (grade in ('PLAY','PASS')),
  regime text,
  event_risk text not null default 'unknown',
  gate_reasons jsonb not null default '[]'::jsonb,
  components jsonb not null default '{}'::jsonb,
  unique (contract_symbol, snapshot_bucket, model_version)
);

create index if not exists options_setup_snapshots_underlying_captured_idx
  on public.options_setup_snapshots (underlying, captured_at desc);
create index if not exists options_setup_snapshots_grade_score_idx
  on public.options_setup_snapshots (grade, profit_score desc, captured_at desc);

alter table public.options_setup_snapshots enable row level security;
revoke all on table public.options_setup_snapshots from anon, authenticated;
grant select, insert, update on table public.options_setup_snapshots to service_role;
grant usage, select on sequence public.options_setup_snapshots_id_seq to service_role;

create table if not exists public.options_paper_trades (
  trade_id uuid primary key,
  setup_snapshot_id bigint references public.options_setup_snapshots(id) on delete set null,
  contract_symbol text not null,
  underlying text not null,
  option_type text not null check (option_type in ('CALL','PUT')),
  expiration date not null,
  strike numeric(18,6) not null,
  qty integer not null check (qty > 0),
  entry_at timestamptz not null,
  entry_price numeric(18,6) not null check (entry_price >= 0),
  profit_score_at_entry numeric(12,6),
  grade_at_entry text check (grade_at_entry in ('PLAY','PASS')),
  model_net_ev_at_entry numeric(18,6),
  status text not null check (status in ('OPEN','CLOSED')),
  exit_at timestamptz,
  exit_price numeric(18,6),
  realized_pnl numeric(18,6),
  close_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists options_paper_trades_status_entry_idx
  on public.options_paper_trades (status, entry_at desc);
create index if not exists options_paper_trades_underlying_entry_idx
  on public.options_paper_trades (underlying, entry_at desc);

alter table public.options_paper_trades enable row level security;
revoke all on table public.options_paper_trades from anon, authenticated;
grant select, insert, update on table public.options_paper_trades to service_role;
