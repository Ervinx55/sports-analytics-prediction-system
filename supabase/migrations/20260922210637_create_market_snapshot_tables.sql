
create table if not exists public.market_snapshot_runs (
  id uuid primary key default gen_random_uuid(),
  captured_at timestamptz not null default now(),
  snapshot_label text,
  requested_leagues text[] not null default '{}',
  event_count integer not null default 0,
  row_count integer not null default 0,
  status text not null default 'ok',
  note text
);

create table if not exists public.market_snapshots (
  id bigint generated by default as identity primary key,
  run_id uuid references public.market_snapshot_runs(id) on delete cascade,
  captured_at timestamptz not null default now(),
  snapshot_label text,
  league text not null,
  event_id text not null,
  starts_at timestamptz,
  away_team text,
  home_team text,
  book text not null,
  market text not null,
  side text not null,
  line numeric,
  odds integer,
  available boolean,
  source text not null default 'mainstream',
  raw jsonb
);

create index if not exists market_snapshots_event_idx
  on public.market_snapshots(event_id, captured_at desc);

create index if not exists market_snapshots_lookup_idx
  on public.market_snapshots(league, event_id, market, side, book, captured_at desc);

create index if not exists market_snapshots_start_idx
  on public.market_snapshots(starts_at);

alter table public.market_snapshot_runs enable row level security;
alter table public.market_snapshots enable row level security;
