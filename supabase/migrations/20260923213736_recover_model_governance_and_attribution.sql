CREATE OR REPLACE FUNCTION public.compute_outcome_attribution_v1(p_outcome text, p_decision_status text, p_clv_signal text, p_context_changed boolean, p_data_quality_problem boolean, p_sharp_warning boolean, p_fusion_state text, p_fusion_conflict text)
 RETURNS jsonb
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO 'pg_catalog', 'public'
AS $function$;
declare
  v_out text := upper(coalesce(p_outcome,'UNKNOWN'));
  v_dec text := upper(coalesce(p_decision_status,'UNKNOWN'));
  v_clv text := upper(coalesce(p_clv_signal,'UNKNOWN'));
  v_attr text;
  v_grade text;
  v_explanation text;
begin
  if v_out='PUSH' then
    return jsonb_build_object(
      'primaryAttribution','PUSH_NO_ATTRIBUTION',
      'processGrade','NEUTRAL',
      'explanation','The wager pushed, so no win/loss attribution is assigned.'
    );
  end if;

  if v_dec='PASS' then
    if v_out='L' then
      v_attr := 'GOOD_PASS';
      v_grade := 'PASS_VALIDATED';
      v_explanation := 'The passed wager would have lost; the pass is validated by the outcome, though the original gate reason remains the causal evidence.';
    elsif v_out='W' then
      v_attr := 'MISSED_WIN';
      v_grade := 'MISSED_OPPORTUNITY';
      v_explanation := 'The passed wager would have won. Review the original gate and market context without treating one missed win as proof that the gate is wrong.';
    else
      v_attr := 'PASS_UNRESOLVED';
      v_grade := 'UNRESOLVED';
      v_explanation := 'The pass outcome cannot be resolved into a win/loss attribution.';
    end if;
  elsif v_dec='PLAY' then
    if v_out='L' then
      if coalesce(p_context_changed,false) then
        v_attr := 'CONTEXT_INVALIDATED_AFTER_DECISION';
        v_grade := 'INVALIDATED';
        v_explanation := 'Material lineup, starter, catcher, opponent, or weather context changed after the decision; the original projection became stale.';
      elsif v_clv='NEGATIVE' then
        v_attr := 'MARKET_MOVED_AGAINST_DECISION';
        v_grade := 'WEAK_PROCESS';
        v_explanation := 'The wager lost and the closing market moved against the ticket, indicating a price/market-process miss.';
      elsif coalesce(p_data_quality_problem,false) then
        v_attr := 'DATA_QUALITY_EXPOSURE';
        v_grade := 'WEAK_PROCESS';
        v_explanation := 'The wager lost while a known data-quality or exact-market-coverage weakness was present.';
      elsif coalesce(p_sharp_warning,false) then
        v_attr := 'SHARP_WARNING_EXPOSURE';
        v_grade := 'WEAK_PROCESS';
        v_explanation := 'The wager lost while a material sharp-market warning was present.';
      elsif v_clv='POSITIVE' then
        v_attr := 'GOOD_PROCESS_BAD_OUTCOME';
        v_grade := 'STRONG_PROCESS';
        v_explanation := 'The wager lost despite beating the closing market. Treat this as a bad outcome with positive process evidence, not an automatic model failure.';
      else
        v_attr := 'MODEL_OR_VARIANCE_UNRESOLVED';
        v_grade := 'UNRESOLVED';
        v_explanation := 'The wager lost without enough closing-market or context evidence to separate model error from ordinary outcome variance.';
      end if;
    elsif v_out='W' then
      if coalesce(p_context_changed,false) then
        v_attr := 'WIN_DESPITE_CONTEXT_INVALIDATION';
        v_grade := 'MIXED_PROCESS';
        v_explanation := 'The wager won, but material context changed after the decision; the win should not validate the stale projection.';
      elsif v_clv='NEGATIVE' then
        v_attr := 'WIN_WITH_NEGATIVE_PROCESS';
        v_grade := 'WEAK_PROCESS';
        v_explanation := 'The wager won even though the closing market moved against the ticket. Do not treat the result as proof of good process.';
      elsif v_clv='POSITIVE' then
        v_attr := 'GOOD_PROCESS_GOOD_OUTCOME';
        v_grade := 'STRONG_PROCESS';
        v_explanation := 'The wager won and beat the closing market, aligning outcome and process.';
      elsif coalesce(p_data_quality_problem,false) or coalesce(p_sharp_warning,false) then
        v_attr := 'WIN_DESPITE_WARNING';
        v_grade := 'MIXED_PROCESS';
        v_explanation := 'The wager won despite a known data-quality or market warning; the result should not erase the warning.';
      else
        v_attr := 'WIN_NEUTRAL_PROCESS';
        v_grade := 'UNRESOLVED';
        v_explanation := 'The wager won, but closing-market evidence is insufficient to grade the decision process.';
      end if;
    else
      v_attr := 'PLAY_UNRESOLVED';
      v_grade := 'UNRESOLVED';
      v_explanation := 'The play does not have a resolved win/loss outcome.';
    end if;
  else
    v_attr := 'UNRESOLVED_DECISION';
    v_grade := 'UNRESOLVED';
    v_explanation := 'The stored decision was not a final PLAY or PASS.';
  end if;

  return jsonb_build_object(
    'primaryAttribution',v_attr,
    'processGrade',v_grade,
    'explanation',v_explanation,
    'clvSignal',v_clv,
    'contextChanged',coalesce(p_context_changed,false),
    'dataQualityProblem',coalesce(p_data_quality_problem,false),
    'sharpWarning',coalesce(p_sharp_warning,false),
    'fusionState',p_fusion_state,
    'fusionConflict',p_fusion_conflict
  );
end;
