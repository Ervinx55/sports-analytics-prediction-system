CREATE OR REPLACE FUNCTION public.refresh_decision_outcome_attribution()
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_catalog'
AS $function$;
declare
  r record;
  v_eval jsonb;
  v_clv_signal text;
  v_clv_metric text;
  v_clv_value numeric;
  v_context boolean;
  v_data_problem boolean;
  v_sharp_warning boolean;
  v_count integer := 0;
begin
  for r in
    select
      tr.observation_id,tr.event_id,tr.game_pk,tr.decision_status,tr.outcome,
      tr.market_label as label,tr.market_type as category,
      g.model_probability,g.market_fair_probability,g.edge_pct_points,g.ev_pct,
      u.classification as uncertainty_class,
      f.fusion_state,f.conflict_code,f.sharp_classification,
      v.starter_change_after_model,v.handedness_change_after_model,
      v.lineup_change_after_model,v.catcher_change_after_model,
      w.weather_change_after_model,
      c.market_to_close_clv_pp,
      dt.timing_bucket
    from public.team_market_results tr
    join public.market_grade_observations g on g.id=tr.observation_id
    left join public.market_uncertainty_shadow u on u.observation_id=tr.observation_id
    left join public.market_decision_fusion_shadow f on f.observation_id=tr.observation_id
    left join public.team_market_verification_shadow v on v.observation_id=tr.observation_id
    left join public.team_market_weather_shadow w on w.observation_id=tr.observation_id
    left join public.sharp_market_clv c on c.observation_id=tr.observation_id
    left join public.decision_timing_shadow dt
      on dt.leg_type='TEAM' and dt.observation_id=tr.observation_id
  loop
    v_clv_value := r.market_to_close_clv_pp;
    v_clv_metric := case when v_clv_value is null then null else 'MARKET_TO_CLOSE_PP' end;
    v_clv_signal := case
      when v_clv_value is null then 'UNKNOWN'
      when v_clv_value >= 0.5 then 'POSITIVE'
      when v_clv_value <= -0.5 then 'NEGATIVE'
      else 'NEUTRAL'
    end;

    v_context := coalesce(r.starter_change_after_model,false)
      or coalesce(r.handedness_change_after_model,false)
      or coalesce(r.lineup_change_after_model,false)
      or coalesce(r.catcher_change_after_model,false)
      or coalesce(r.weather_change_after_model,false)
      or coalesce(r.fusion_state,'')='REMODEL';

    v_data_problem := coalesce(r.uncertainty_class,'')='INCOMPLETE'
      or coalesce(r.conflict_code,'') in ('INPUTS_INCOMPLETE','FRAGILE_EDGE');

    v_sharp_warning := coalesce(r.sharp_classification,'') in (
      'REAL_SHARP_DISAGREEMENT','SOURCE_QUALITY_PROBLEM'
    );

    v_eval := public.compute_outcome_attribution_v1(
      r.outcome,r.decision_status,v_clv_signal,v_context,v_data_problem,
      v_sharp_warning,r.fusion_state,r.conflict_code
    );

    insert into public.decision_outcome_attribution (
      leg_type,observation_id,evaluated_at,event_id,game_pk,label,category,
      decision_status,outcome,primary_attribution,process_grade,explanation,
      clv_signal,clv_metric,clv_value,context_changed,data_quality_problem,
      sharp_warning,fusion_state,fusion_conflict,timing_bucket,evidence
    ) values (
      'TEAM',r.observation_id,now(),r.event_id,r.game_pk,r.label,r.category,
      r.decision_status,r.outcome,v_eval->>'primaryAttribution',v_eval->>'processGrade',
      v_eval->>'explanation',v_clv_signal,v_clv_metric,v_clv_value,v_context,
      v_data_problem,v_sharp_warning,r.fusion_state,r.conflict_code,r.timing_bucket,
      jsonb_build_object(
        'modelProbability',r.model_probability,
        'marketProbability',r.market_fair_probability,
        'edgePp',r.edge_pct_points,
        'evPct',r.ev_pct,
        'uncertaintyClass',r.uncertainty_class,
        'sharpClassification',r.sharp_classification
      )
    )
    on conflict (leg_type,observation_id) do update
    set evaluated_at=excluded.evaluated_at,
        decision_status=excluded.decision_status,
        outcome=excluded.outcome,
        primary_attribution=excluded.primary_attribution,
        process_grade=excluded.process_grade,
        explanation=excluded.explanation,
        clv_signal=excluded.clv_signal,
        clv_metric=excluded.clv_metric,
        clv_value=excluded.clv_value,
        context_changed=excluded.context_changed,
        data_quality_problem=excluded.data_quality_problem,
        sharp_warning=excluded.sharp_warning,
        fusion_state=excluded.fusion_state,
        fusion_conflict=excluded.fusion_conflict,
        timing_bucket=excluded.timing_bucket,
        evidence=excluded.evidence;

    v_count := v_count+1;
  end loop;

  for r in
    select
      pr.observation_id,pr.event_id,pr.game_pk,pr.outcome,
      p.status as decision_status,p.label,p.stat_id as category,
      p.model_probability,p.market_fair_probability,p.edge_pct_points,p.ev_pct,
      p.data_quality,p.exact_line_book_count,p.paired_books,
      f.fusion_state,f.conflict_code,
      v.catcher_change_after_model,v.opposing_starter_change_after_model,
      v.opposing_handedness_change_after_model,
      w.weather_change_after_model,
      c.line_clv_units,c.fair_probability_clv_pp,c.same_book_price_clv_pp,
      c.clv_classification,
      dt.timing_bucket
    from public.player_prop_results pr
    join public.player_prop_observations p on p.id=pr.observation_id
    left join public.player_prop_decision_fusion_shadow f on f.observation_id=pr.observation_id
    left join public.player_prop_verification_shadow v on v.observation_id=pr.observation_id
    left join public.player_prop_weather_shadow w on w.observation_id=pr.observation_id
    left join public.player_prop_clv c on c.observation_id=pr.observation_id
    left join public.decision_timing_shadow dt
      on dt.leg_type='PROP' and dt.observation_id=pr.observation_id
  loop
    if r.line_clv_units is not null and abs(r.line_clv_units)>=0.49 then
      v_clv_value := r.line_clv_units;
      v_clv_metric := 'LINE_CLV_UNITS';
      v_clv_signal := case when r.line_clv_units>0 then 'POSITIVE' else 'NEGATIVE' end;
    else
      v_clv_value := coalesce(r.fair_probability_clv_pp,r.same_book_price_clv_pp);
      v_clv_metric := case
        when r.fair_probability_clv_pp is not null then 'FAIR_PROBABILITY_CLV_PP'
        when r.same_book_price_clv_pp is not null then 'SAME_BOOK_PRICE_CLV_PP'
        else null
      end;
      v_clv_signal := case
        when v_clv_value is null then 'UNKNOWN'
        when v_clv_value>=0.5 then 'POSITIVE'
        when v_clv_value<=-0.5 then 'NEGATIVE'
        else 'NEUTRAL'
      end;
    end if;

    v_context := coalesce(r.catcher_change_after_model,false)
      or coalesce(r.opposing_starter_change_after_model,false)
      or coalesce(r.opposing_handedness_change_after_model,false)
      or coalesce(r.weather_change_after_model,false)
      or coalesce(r.fusion_state,'')='REMODEL';

    v_data_problem := coalesce(r.data_quality,0)<0.75
      or coalesce(r.exact_line_book_count,0)<2
      or coalesce(r.paired_books,0)<1
      or coalesce(r.conflict_code,'') in ('DATA_QUALITY_FAIL','MARKET_COVERAGE_FAIL');

    v_eval := public.compute_outcome_attribution_v1(
      r.outcome,r.decision_status,v_clv_signal,v_context,v_data_problem,
      false,r.fusion_state,r.conflict_code
    );

    insert into public.decision_outcome_attribution (
      leg_type,observation_id,evaluated_at,event_id,game_pk,label,category,
      decision_status,outcome,primary_attribution,process_grade,explanation,
      clv_signal,clv_metric,clv_value,context_changed,data_quality_problem,
      sharp_warning,fusion_state,fusion_conflict,timing_bucket,evidence
    ) values (
      'PROP',r.observation_id,now(),r.event_id,r.game_pk,r.label,r.category,
      r.decision_status,r.outcome,v_eval->>'primaryAttribution',v_eval->>'processGrade',
      v_eval->>'explanation',v_clv_signal,v_clv_metric,v_clv_value,v_context,
      v_data_problem,false,r.fusion_state,r.conflict_code,r.timing_bucket,
      jsonb_build_object(
        'modelProbability',r.model_probability,
        'marketProbability',r.market_fair_probability,
        'edgePp',r.edge_pct_points,
        'evPct',r.ev_pct,
        'dataQuality',r.data_quality,
        'exactLineBookCount',r.exact_line_book_count,
        'pairedBooks',r.paired_books,
        'clvClassification',r.clv_classification
      )
    )
    on conflict (leg_type,observation_id) do update
    set evaluated_at=excluded.evaluated_at,
        decision_status=excluded.decision_status,
        outcome=excluded.outcome,
        primary_attribution=excluded.primary_attribution,
        process_grade=excluded.process_grade,
        explanation=excluded.explanation,
        clv_signal=excluded.clv_signal,
        clv_metric=excluded.clv_metric,
        clv_value=excluded.clv_value,
        context_changed=excluded.context_changed,
        data_quality_problem=excluded.data_quality_problem,
        fusion_state=excluded.fusion_state,
        fusion_conflict=excluded.fusion_conflict,
        timing_bucket=excluded.timing_bucket,
        evidence=excluded.evidence;

    v_count := v_count+1;
  end loop;

  return v_count;
end;
